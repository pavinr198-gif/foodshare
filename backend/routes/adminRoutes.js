import {Router} from 'express';
import {createUser,users,userDetails,updateUserStatus,deleteUser,createBusiness,businesses,businessDetails,pending,approve,reject,updateBusinessStatus,deleteBusiness,foods,requests,reports,statistics,removeFood} from '../controllers/adminController.js';
import {auth,roles} from '../middleware/auth.js';
const r=Router();
r.use(auth,roles('admin'));
r.post('/users',createUser);
r.get('/users',users);
r.get('/users/:id',userDetails);
r.patch('/users/:id/status',updateUserStatus);
r.delete('/users/:id',deleteUser);
r.post('/businesses',createBusiness);
r.get('/businesses',businesses);
r.get('/businesses/pending',pending);
r.get('/businesses/:id',businessDetails);
r.put('/businesses/:id/approve',approve);
r.put('/businesses/:id/reject',reject);
r.patch('/businesses/:id/status',updateBusinessStatus);
r.delete('/businesses/:id',deleteBusiness);
r.get('/foods',foods);
r.delete('/foods/:id',removeFood);
r.get('/requests',requests);
r.get('/reports',reports);
r.get('/statistics',statistics);
export default r;
